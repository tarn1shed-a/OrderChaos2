ROOT=Path(__file__).resolve().parents[1]
FORMAT='oc2-tutorial-npc-additional-candidate-v1'
EFFECTS={'lt_cull_pal_normal_trans.bdae':{'ALPHA_TEST','RIM_LIGHT'},
         'lt_cull_pal_normal_solid.bdae':{'RIM_LIGHT'}}


def original_material(reader,name):
    count,table=reader.section(172)
    found=[table+i*80 for i in range(count)if reader.string(reader.q(table+i*80))==name]
    if len(found)!=1:raise ValueError('Missing or duplicate original material')
    at=found[0];effect=reader.string(reader.q(at+8));effect_name=reader.string(reader.q(at+16))
    if effect not in EFFECTS or effect_name!='#'+Path(effect).stem+'-fx':
        raise ValueError('Unreviewed additional NPC effect')
    count,props=reader.u(at+32),reader.rel(at+36)
    if not 0<count<=64:raise ValueError('Bounded original material properties required')
    nt,textures=reader.section(148);scalars={};samplers={};seen=set();technique=None
    for i in range(count):
        p=props+i*32;field=reader.string(reader.q(p));kind=reader.u(p+16);value=reader.rel(p+28)
        if field in seen:raise ValueError('Duplicate original material property')
        seen.add(field)
        if field in SCALARS:
            if kind!=8 or reader.u(p+20)!=1:raise ValueError('Original scalar encoding differs')
            scalars[field]=reader.unpack('f',value)[0]
        elif field in SAMPLERS:
            pointer=reader.rel(value)
            if (kind!=17 or reader.u(p+20)!=1 or not textures<=pointer<textures+nt*32 or
                    (pointer-textures)%32):raise ValueError('Original sampler binding differs')
            samplers[field]=reader.string(reader.q(pointer+16))
        elif field.endswith('/CurrentTechnique'):
            if kind!=28 or reader.u(p+20)!=1:raise ValueError('Original technique encoding differs')
            technique=reader.named_technique(value)
        else:raise ValueError('Additional material property requires separate recovery: '+field)
    if set(scalars)!=set(SCALARS)or set(samplers)!=set(SAMPLERS)or technique is None:
        raise ValueError('Incomplete original additional NPC material')
    return {'effectPath':effect,'effectName':effect_name,'scalars':scalars,'sourceSamplers':samplers,
            'sourceMaterialRecordOffset':at,'sourceTechniqueName':technique['name'],
            'sourceTechniqueValueWord0':technique['valueWord0']}


def export(image,source,output,*,three):
    output=local_output(output)
    if output.exists():raise ValueError('Preserve existing candidates')
    verify_attributes(image);verify_fx(image)
    evidence=recover(image,source);sources=Sources(source)
    output.mkdir(parents=True);(output/'assets').mkdir();textures={}
    def write(name,value):
        p=output/name;p.parent.mkdir(parents=True,exist_ok=True)
        p.write_text(json.dumps(value,ensure_ascii=False,separators=(',',':'),allow_nan=False)+'\n')
        return '/'+name
    def extract(path,temporary):
        p=Path(temporary)/path;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(sources.read(path));return p
    def texture(path):
        if path not in textures:
            raw=sources.read(path);name='assets/'+hashlib.sha256(raw).hexdigest()+'.png'
            decode(raw).save(output/name);textures[path]='/'+name
        return textures[path]
    def materials(reader,data,temporary):
        records=[]
        for index,m in enumerate(data['materials']):
            record=original_material(reader,m['name'])
            if record['sourceSamplers']!=m['samplers']:raise ValueError('Sampler reader disagreement')
            fx=BDAE(extract(record['effectPath'],temporary));declaration=effect_render_state(fx)
            if declaration['effectName']!=record['effectName'][1:]:raise ValueError('Original effect identity differs')
            profiles=declaration['profiles'];expected_defines=EFFECTS[record['effectPath']]
            for p in profiles:
                for stage,shader in [('vertexShader','lt_pal_normal_vs.glsl'),('fragmentShader','lt_pal_normal_fs.glsl')]:
                    if p[stage]['file']!=shader or set(p[stage]['defines'])!=expected_defines:
                        raise ValueError('Original shader/define relationship differs')
                    if hashlib.sha256(sources.read(shader)).hexdigest()!=SHADER_SHA256[shader]:
                        raise ValueError('Original shader content changed')
                if p['technique']!=record['sourceTechniqueName']:raise ValueError('Unresolved material technique')
            if profiles[0]['state']!=profiles[1]['state']:raise ValueError('Device profile states diverge')
            state=profiles[0]['state']
            if state['blendEnabled'] or state['cullFaceGL']!=0x405 or not state['depthWriteEnabled']:
                raise ValueError('Additional original pass needs a new renderer branch')
            records.append({'index':index,**record,'defines':sorted(expected_defines),
                'samplers':{k:texture(v)for k,v in record['sourceSamplers'].items()},
                'alphaTest':.5 if 'ALPHA_TEST'in expected_defines else 0,
                'doubleSided':not state['cullEnabled'],'sourceEffectProfiles':declaration,
                'fullNativeFrameRestored':False})
        return records
    entries=[]
    with tempfile.TemporaryDirectory(prefix='oc2-additional-npc-')as temporary:
        for row in evidence['entries']:
            entry=row['entry'];path=row['singleModel']['request']['path']
            reader=BDAE(extract(path,temporary));data=source_tangent_basis(reader,reader.parse())
            data['source']=path;data['rig']=recover_skin(reader,data)
            if len(data['meshes'])!=1 or len(data['rig']['skins'])!=1:
                raise ValueError('Only complete one-mesh source models are in this batch')
            anim_path=path.rsplit('/',1)[0]+'/anim/animations.bdae'
            animation=BDAEAnimation(extract(anim_path,temporary));decoded=animation.parse(['idle']);node_map=aliases(data['rig']['nodes'])
            clips=[]
            for clip in decoded['clips']:
                tracks=[]
                for t in clip['tracks']:
                    if t['node']not in node_map:raise ValueError('Original idle target missing')
                    tracks.append({**copy.deepcopy(t),'node':node_map[t['node']]})
                clips.append({**clip,'tracks':tracks})
            data.update({'format':'bdae946-character-v1','clips':clips,
                'sourceAdditionalNPC':{'format':FORMAT,'entry':entry,'originalDefaultOnly':True,
                    'singleModelBranchCPU':row['singleModel']['request'],
                    'visibleMeshIndices':[0],'bodyPart37BranchUsed':False,'weaponMounted':False,
                    'liveGUID':None,'worldPlacement':None,'questAvailability':None},
                'animationBinding':{'source':anim_path,'sourceRange':next(r for r in animation.ranges()if r['name']=='idle'),
                    'defaultRequestCPU':row['defaultIdle'],'sourceTrackValuesPreserved':True,
                    'browserClockLoopAndCameraAreReviewAdapters':True}})
            item={'entry':entry,'name':row['name'],'model':write('assets/npc'+str(entry)+'.json',data),
                'materials':materials(reader,data,temporary),'visibleMeshIndices':[0],
                'idleDuration':clips[0]['duration'],'nodeCount':len(data['rig']['nodes']),
                'triangles':sum(m['triangleCount']for m in data['meshes']),
                'sourceDisplay':row['original']['appearanceCandidates'][0]['display'],
                'questObjectiveRelationship':{'questId':202,
                    'orderedStep':row['questObjectiveReferences'][0]['objective']['step'],
                    'objectiveIndex':row['questObjectiveReferences'][0]['objective']['obj_idx'],
                    'notCompletionProof':True},
                'weapon':None,'runtimeGUID':None,'worldPlacement':None,'activitySpawn':None,'questAvailability':None}
            if entry==970:
                displays=decode_ftable(sources.read('tables/itemdisplayinfo.tbl'),'ID')
                models=decode_ftable(sources.read('tables/itemmodeldata.tbl'),'ID')
                display=next(r for r in displays['rows']if r['ID']==200010)
                model=next(r for r in models['rows']if r['ID']==display['ModelHumanMale'])
                weapon_path=model['ModelPath'];wreader=BDAE(extract(weapon_path,temporary))
                weapon=source_tangent_basis(wreader,wreader.parse());weapon['source']=weapon_path
                weapon['sourceNodes']=read_nodes(wreader)
                item['weapon']={'itemKey':200010,'sourceDisplay':display,'sourceModel':model,
                    'model':write('assets/weapon200010.json',weapon),'materials':materials(wreader,weapon,temporary),
                    'originalPairRequests':row['weaponPairRequests'],
                    'mounted':False,'mountTransform':None,'posture':None,
                    'scope':'Verified separate original asset; do not attach using an invented transform.'}
            entries.append(item)
    manifest={'format':FORMAT,'entries':entries,'liveActor':False,
        'scope':'Two original default single-model asset candidates; no world, activity or quest-state construction.',
        'reviewAdapters':['WebGL skeleton and original material formula rewrite','Neutral lighting and camera/framing','Host idle clock/repeat'],
        'colors':{'skin':[1,1,1],'hair':[1,1,1]}}
    write('manifest.json',manifest);write('native-private.json',evidence);write('sources-private.json',sources.proofs)
    for name in ['three.module.js','three.core.js']:shutil.copyfile(three/name,output/name)
    shutil.copyfile(ROOT/'tools/preview/source-npc-material.js',output/'source-npc-material.js')
    shutil.copyfile(ROOT/'tools/preview/source-npc-additional-preview.js',output/'source-npc-additional-preview.js')
    (output/'index.html').write_text('''<!doctype html><html lang="zh-CN"><meta charset="utf-8"><title>新手747/970原资源独立审阅</title><meta name="viewport" content="width=device-width,initial-scale=1"><style>html,body{margin:0;height:100%;background:#14191d;color:#e5e7e6;font:15px system-ui}canvas{display:block;width:100%;height:100%}aside{position:absolute;left:24px;top:24px;max-width:350px}small{color:#c9b388}h1{font-size:22px}p{color:#bec8c8;line-height:1.5}button{background:#26373f;color:#e8e7df;border:1px solid #53666c;border-radius:4px;padding:9px;margin-right:8px;cursor:pointer}button[aria-pressed=true]{border-color:#cfb075}footer{position:absolute;left:24px;bottom:20px;color:#96a7ab;font-size:12px}</style><canvas></canvas><aside><small>原资源 · 独立模型审阅</small><h1>747 / 970</h1><div id="choices"></div><p id="status">读取原资源…</p></aside><footer>拖动旋转 · 滚轮缩放 · 默认idle审阅；活动实例、世界位置与任务状态保持未知</footer><script type="module" src="/source-npc-additional-preview.js"></script></html>''')
    records={str(p.relative_to(output)):{'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()}
        for p in sorted(output.rglob('*'))if p.is_file()}
    write('package-files.json',{'format':FORMAT,'privateOnly':True,'files':records})
    return {'output':str(output),'entries':[r['entry']for r in entries],'files':len(records)+1,
            'textures':len(textures),'productionChanged':False}


