import {CastMachine} from './cast-machine.mjs';

// Native client state progression is separated from the local server policy
// which acknowledges it and from the prototype's delayed damage calculation.
export class SpellRuntime {
  constructor(profile,{executions,emit,check,hit}){
    this.profile=profile;this.executions=executions;this.emit=emit;this.check=check;this.hit=hit;this.pending=new Map();
  }
  start(ws,skill,cast){
    const machine=new CastMachine(skill.native,cast.startedAt,{watchdogMs:this.profile.serverWaitExtraMs});
    const record={ws,skill,cast,machine,hit:false};this.pending.set(cast.id,record);this.executions.set(ws.player.id,record);
    this.publish(record,cast.startedAt,false);return cast;
  }
  publish(r,now,event=true){
    Object.assign(r.cast,r.machine.snapshot());
    if(this.executions.get(r.ws.player.id)===r)r.ws.player.cast=r.cast;
    if(event)this.emit({type:'combat',action:'skill-stage',attackerId:r.ws.player.id,targetId:r.cast.targetId,cast:r.cast,serverTime:now});
  }
  cancel(r,reason,now){
    if(this.pending.get(r.cast.id)!==r)return false;
    r.machine.cancel(reason,now);this.publish(r,now,false);
    this.emit({type:'combat',action:'skill-cancel',attackerId:r.ws.player.id,targetId:r.cast.targetId,
      skillId:r.cast.skillId,castId:r.cast.id,message:reason,serverTime:now});this.remove(r);return true;
  }
  remove(r){
    this.pending.delete(r.cast.id);
    if(this.executions.get(r.ws.player.id)===r)this.executions.delete(r.ws.player.id);
    if(r.ws.player.cast?.id===r.cast.id)r.ws.player.cast=null;
  }
  move(ws,input,now){
    const r=this.executions.get(ws.player.id);
    if(r?.machine.movement.interruptOnMove&&(input.x||input.y))this.cancel(r,'移动中断施法',now);
  }
  tick(now){
    for(const r of this.pending.values()){
      const reason=this.check(r,now);if(reason){this.cancel(r,reason,now);continue;}
      const before=r.machine.revision;
      // These are acknowledgements generated by OUR server from source table
      // durations. They stand in for missing original SMSG_CastSucceed/
      // ChannelStart/ChannelUpdate messages, not a recovered original server.
      if(r.machine.stage===1&&now>=r.cast.releaseAt)r.machine.signal(r.skill.native.channelMs>0?3:2,r.cast.releaseAt);
      if(r.machine.stage===3&&now>=r.cast.releaseAt+r.skill.native.channelMs)r.machine.signal(6,r.cast.releaseAt+r.skill.native.channelMs);
      r.machine.tick(now);
      if(r.machine.stage===-2){this.cancel(r,r.machine.reason,now);continue;}
      if(before!==r.machine.revision){
        this.publish(r,now);
        if(r.machine.movement.stopOnEnter)r.ws.input={x:0,y:0};
      }
      if(r.machine.done&&this.executions.get(r.ws.player.id)===r){
        this.executions.delete(r.ws.player.id);r.ws.player.lastCast=structuredClone(r.cast);
        if(r.ws.player.cast?.id===r.cast.id)r.ws.player.cast=null;
      }
      if(!r.hit&&now>=r.cast.impactAt){r.hit=true;this.hit(r,now);}
      if(r.machine.done&&r.hit)this.remove(r);
    }
  }
  snapshot(){return [...this.pending.values()].filter(r=>!r.hit).map(r=>({attackerId:r.ws.player.id,cast:structuredClone(r.cast)}));}
}
